"""FDMNES input-file generator (plan stage 3, now frozen for K-edge/CIF jobs).

This is a direct refactor of the notebook you were debugging
(``FDMNES_Input_Generator_Ni_Co_HHTP.ipynb``): the keyword order and text
format of ``build_fdmnes_input`` are unchanged on purpose for CIF-based
jobs, so files generated by this module are byte-for-byte compatible with
the ones the notebook produced (including the one that already ran,
``NiHHTP_input.txt``) as long as you don't set any of the newer L-edge
fields (``edge``, ``molecule``, or the extra ``ProtocolSettings`` below) --
those are all no-ops/omitted unless you use them.

What changed versus the notebook:
  * Settings live in ``JobSpec`` + ``ProtocolSettings`` / ``AbsorberSettings``
    instead of module-level globals, so many structures can be generated
    without editing a cell each time.
  * Validation raises early with clear errors instead of silently
    continuing.
  * A ``generate_batch`` helper replaces the "OPTIONAL BATCH EXAMPLE" cell.
  * Structure input can be a CIF file (``JobSpec.structure_file``, the
    original Ni-HHTP/Co-HHTP workflow) *or* an isolated-molecule structure
    built from a .xyz file (``JobSpec.molecule`` / ``xyz_parser.parse_xyz``,
    for the CuTAPP/ZnTAPP-pyridine L-edge jobs) -- see ``JobSpec`` for
    which one to set.
  * ``JobSpec.edge`` (e.g. "L23") emits FDMNES's "Edge" keyword; leave it
    None for the default K edge.

Once you've confirmed a generated input reproduces your manual FDMNES run,
treat the CIF/K-edge *text format* produced here as frozen (per the plan:
"freeze the generator format and move to automatic execution"). Only the
``ProtocolSettings`` values should still change as you tune the standard
protocol.
"""

from __future__ import annotations

from pathlib import Path
from typing import Iterable, List, Optional, Union

from .config import AbsorberSettings, ProtocolSettings
from .models import JobSpec, MoleculeStructure


def _molecule_block_lines(molecule: MoleculeStructure) -> List[str]:
    a, b, c, alpha, beta, gamma = molecule.cell
    lines = ["Molecule", f"  {a} {b} {c} {alpha} {beta} {gamma}"]
    for z, x, y, zc in molecule.atoms:
        lines.append(f"   {z:>3d}   {x:.8f}   {y:.8f}   {zc:.8f}")
    lines.append("")
    return lines


def build_fdmnes_input(
    structure: Union[Path, MoleculeStructure],
    absorber: AbsorberSettings,
    filout: Path,
    protocol: ProtocolSettings,
) -> str:
    """Return the FDMNES input-file text for one job. Pure function, no I/O.

    ``structure`` is either a CIF path (emits "Cif_file") or a
    ``MoleculeStructure`` (emits "Molecule" with the atom list).

    Keyword order for a plain K-edge/CIF job (no edge, no L-edge extras
    set) matches the original notebook exactly: Filout, Range, Radius,
    [Green], [PBE96], [SCF], [Quadrupole], absorber block, Cif_file,
    [Convolution], End -- this is the frozen format. Every field added for
    L-edge/molecule jobs (Vmax, TDDFT, Overad, Spinorbit, Edge, Estart) is
    only ever inserted when you actually set it, so it never changes
    output for jobs that don't use it.
    """
    z = absorber.atomic_number
    is_molecule = isinstance(structure, MoleculeStructure)

    lines: List[str] = []
    if is_molecule:
        # Matches the header style of your CuTAPP/ZnTAPP reference inputs.
        lines.append("! FDMNES input generated from XYZ using Python")
        source = structure.source_xyz if structure.source_xyz else "(inline molecule)"
        lines.append(f"! Source structure: {source}")
    else:
        # Unchanged on purpose -- this is the frozen K-edge/CIF header text.
        lines.append(f"! {absorber.element}-HHTP FDMNES input generated by Python")
    lines.append("")

    lines += ["Filout", f"  {filout}", ""]
    lines += ["Range", f"  {protocol.energy_range}", ""]
    lines += ["Radius", f"  {protocol.radius:.3f}", ""]

    if protocol.use_green:
        lines += ["Green", ""]
    if protocol.vmax is not None:
        lines += ["Vmax", f"  {protocol.vmax}", ""]
    if protocol.use_pbe96:
        lines += ["PBE96", ""]
    if protocol.use_scf:
        lines += ["SCF", ""]
    if protocol.use_quadrupole:
        lines += ["Quadrupole", ""]
    if protocol.use_tddft:
        lines += ["TDDFT", ""]
    if protocol.overad is not None:
        lines += ["Overad", f"  {protocol.overad}", ""]
    if protocol.use_spinorbit:
        lines += ["Spinorbit", ""]

    if absorber.mode == "all":
        lines += ["Z_absorber", f"  {z}", ""]
    else:
        lines += ["Absorber", f"  {absorber.index}", ""]

    if absorber.edge:
        lines += ["Edge", f"  {absorber.edge}", ""]

    if is_molecule:
        lines += _molecule_block_lines(structure)
    else:
        lines += ["Cif_file", f"  {structure}", ""]

    if protocol.estart is not None:
        lines += ["Estart", f"  {protocol.estart}", ""]

    if protocol.use_convolution:
        lines += ["Convolution", ""]

    lines += ["End", ""]
    return "\n".join(lines)


def generate_input_file(
    job: JobSpec,
    protocol: ProtocolSettings,
    warn_if_structure_missing: bool = True,
) -> str:
    """Build and write one job's FDMNES input file. Returns the text written.

    Mirrors the notebook's VALIDATION + WRITE cells: warns (does not raise)
    if a CIF-mode job's structure file is not currently reachable, since the
    codebase may be prepared on one machine and run on another -- but
    raises on genuinely invalid settings (bad element, bad radius, bad
    absorber index). Molecule-mode jobs (``job.molecule`` set, e.g. via
    ``xyz_parser.parse_xyz``) have no such check: the atoms are already
    parsed into memory by the time a JobSpec exists.
    """
    absorber = AbsorberSettings(
        element=job.element, mode=job.absorber_mode, index=job.absorber_index, edge=job.edge
    )
    if protocol.radius <= 0:
        raise ValueError("radius must be greater than zero.")

    structure = job.molecule if job.molecule is not None else job.structure_file

    if (
        warn_if_structure_missing
        and job.structure_file is not None
        and not job.structure_file.exists()
    ):
        print(
            f"WARNING [{job.name}]: CIF file does not currently exist at:\n"
            f"  {job.structure_file}"
        )

    text = build_fdmnes_input(
        structure=structure,
        absorber=absorber,
        filout=job.filout,
        protocol=protocol,
    )

    job.input_file.parent.mkdir(parents=True, exist_ok=True)
    job.filout.parent.mkdir(parents=True, exist_ok=True)
    job.input_file.write_text(text, encoding="utf-8", newline="\n")

    return text


def generate_batch(
    jobs: Iterable[JobSpec],
    protocol: ProtocolSettings,
    per_job_protocol: Optional[dict] = None,
) -> List[JobSpec]:
    """Generate input files for several structures in one call.

    Replaces the notebook's commented-out "OPTIONAL BATCH EXAMPLE" cell.
    ``per_job_protocol`` optionally maps a job name to a
    ``ProtocolSettings`` override (e.g. testing one structure at a larger
    radius) while everything else uses the shared ``protocol``.
    """
    per_job_protocol = per_job_protocol or {}
    jobs = list(jobs)
    for job in jobs:
        this_protocol = per_job_protocol.get(job.name, protocol)
        generate_input_file(job, this_protocol)
        print(f"Created: {job.input_file}")
    return jobs


def write_fdmfile(input_files: Iterable[Path], destination: Path) -> Path:
    """Write a standalone ``fdmfile.txt`` listing the given input files.

    Note: FDMNES requires ``fdmfile.txt`` to sit in the *same directory as
    the executable* when it runs (see the manual's "Running" section) --
    this helper is provided for manual testing/copying. For automated runs,
    ``runner.FdmnesRunner`` writes fdmfile.txt directly next to the
    executable it launches, so you normally don't need to call this
    yourself.
    """
    input_files = list(input_files)
    destination.parent.mkdir(parents=True, exist_ok=True)
    body = f"{len(input_files)}\n" + "\n".join(str(p) for p in input_files) + "\n"
    destination.write_text(body, encoding="utf-8", newline="\n")
    return destination
