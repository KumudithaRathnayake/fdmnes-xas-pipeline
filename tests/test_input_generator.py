"""Tests for the frozen input generator.

The reference text in EXPECTED_* below matches the format produced by the
original notebook (FDMNES_Input_Generator_Ni_Co_HHTP.ipynb) and the file it
already generated successfully (NiHHTP_input.txt), just with the values
from these tests substituted in. If a future change to input_generator.py
breaks this test, that's the "freeze the generator format" tripwire from
the plan -- make sure the change is deliberate.
"""

from pathlib import Path

import pytest

from fdmnes_pipeline.config import AbsorberSettings, ProtocolSettings
from fdmnes_pipeline.input_generator import build_fdmnes_input, generate_batch, generate_input_file
from fdmnes_pipeline.models import JobSpec


def test_build_fdmnes_input_all_absorber_matches_notebook_format():
    protocol = ProtocolSettings(radius=7.5, use_convolution=True)
    absorber = AbsorberSettings(element="Ni", mode="all")

    text = build_fdmnes_input(
        structure=Path("/x/Ni_4slab_2b2MOF-ai3.cif"),
        absorber=absorber,
        filout=Path("/x/NiHHTP_output"),
        protocol=protocol,
    )

    expected = (
        "! Ni-HHTP FDMNES input generated by Python\n"
        "\n"
        "Filout\n"
        "  /x/NiHHTP_output\n"
        "\n"
        "Range\n"
        "  -5.0 0.2 10.0 0.5 25.0 1.0 60.0 2.0 100.0\n"
        "\n"
        "Radius\n"
        "  7.500\n"
        "\n"
        "Z_absorber\n"
        "  28\n"
        "\n"
        "Cif_file\n"
        "  /x/Ni_4slab_2b2MOF-ai3.cif\n"
        "\n"
        "Convolution\n"
        "\n"
        "End\n"
    )
    assert text == expected


def test_build_fdmnes_input_selected_absorber_uses_absorber_keyword():
    protocol = ProtocolSettings(use_convolution=False)
    absorber = AbsorberSettings(element="Co", mode="selected", index=3)

    text = build_fdmnes_input(
        structure=Path("/x/Co.cif"),
        absorber=absorber,
        filout=Path("/x/out"),
        protocol=protocol,
    )

    assert "Absorber\n  3\n" in text
    assert "Z_absorber" not in text
    assert "Convolution" not in text


def test_build_fdmnes_input_optional_keywords_toggle():
    protocol = ProtocolSettings(
        use_green=True, use_pbe96=True, use_scf=True, use_quadrupole=True, use_convolution=True
    )
    absorber = AbsorberSettings(element="Ni", mode="all")
    text = build_fdmnes_input(Path("/x/a.cif"), absorber, Path("/x/out"), protocol)

    for keyword in ("Green", "PBE96", "SCF", "Quadrupole", "Convolution"):
        assert f"{keyword}\n" in text


def test_atomic_numbers_ni_co():
    assert AbsorberSettings(element="Ni").atomic_number == 28
    assert AbsorberSettings(element="Co").atomic_number == 27


def test_unknown_element_raises():
    with pytest.raises(ValueError):
        AbsorberSettings(element="Xx")


def test_generate_input_file_writes_to_disk(tmp_path):
    job = JobSpec(
        name="test_job",
        structure_file=tmp_path / "missing.cif",  # deliberately missing -> should warn, not raise
        element="Ni",
        filout=tmp_path / "out" / "test_FDM",
        input_file=tmp_path / "out" / "test_input.txt",
    )
    protocol = ProtocolSettings()

    text = generate_input_file(job, protocol)

    assert job.input_file.exists()
    assert job.input_file.read_text() == text
    assert "Z_absorber" in text
    assert text.endswith("End\n")


def test_generate_input_file_rejects_zero_radius(tmp_path):
    job = JobSpec(
        name="bad_radius",
        structure_file=tmp_path / "a.cif",
        element="Ni",
        filout=tmp_path / "out",
        input_file=tmp_path / "in.txt",
    )
    with pytest.raises(ValueError):
        generate_input_file(job, ProtocolSettings(radius=0))


def test_generate_batch_writes_all_jobs(tmp_path):
    jobs = [
        JobSpec(
            name=f"job_{i}",
            structure_file=tmp_path / f"{i}.cif",
            element="Ni" if i % 2 == 0 else "Co",
            filout=tmp_path / f"out_{i}" / "FDM",
            input_file=tmp_path / f"out_{i}" / "input.txt",
        )
        for i in range(3)
    ]
    generate_batch(jobs, ProtocolSettings())
    for job in jobs:
        assert job.input_file.exists()


def test_generate_batch_per_job_override(tmp_path):
    job_a = JobSpec(
        name="a",
        structure_file=tmp_path / "a.cif",
        element="Ni",
        filout=tmp_path / "a_out",
        input_file=tmp_path / "a_input.txt",
    )
    job_b = JobSpec(
        name="b",
        structure_file=tmp_path / "b.cif",
        element="Ni",
        filout=tmp_path / "b_out",
        input_file=tmp_path / "b_input.txt",
    )
    default_protocol = ProtocolSettings(radius=5.0)
    override_protocol = ProtocolSettings(radius=9.0)

    generate_batch(
        [job_a, job_b],
        default_protocol,
        per_job_protocol={"b": override_protocol},
    )

    assert "Radius\n  5.000" in job_a.input_file.read_text()
    assert "Radius\n  9.000" in job_b.input_file.read_text()
